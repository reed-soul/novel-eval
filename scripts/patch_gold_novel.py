for new_c, old_c in patches:
    # 查找匹配的 revision
    target_substr = old_c[:30]
    c.execute("SELECT id, content FROM chapter_revision WHERE content LIKE ?", (f'%{target_substr}%',))
    rows = c.fetchall()
    for rev_id, content in rows:
        if old_c in content:
            updated = content.replace(old_c, new_c)
            c.execute("UPDATE chapter_revision SET content = ? WHERE id = ?", (updated, rev_id))
            print(f"已更新数据库 revision: {rev_id}")

conn.commit()
